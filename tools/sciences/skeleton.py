def topic_strings(field=None):
    """'Area > Topic' for every topic, in site order (optionally for one field)."""
    return [f"{a['name']} > {t}" for a in AREAS if field in (None, a['field']) for t in a['topics']]


if __name__ == '__main__':
    import collections
    names = [t for a in AREAS for t in a['topics']]
    dup = [n for n, c in collections.Counter(names).items() if c > 1]
    assert not dup, dup
    assert len({a['code'] for a in AREAS}) == len(AREAS)
    assert len({a['name'] for a in AREAS}) == len(AREAS)
    groups = {g for _, g, _ in GROUPS}
    assert all(a['group'] in groups for a in AREAS)
    for f in FIELDS:
        aa = [a for a in AREAS if a['field'] == f]
        print(f'{f}: {len(aa)} areas, {sum(len(a["topics"]) for a in aa)} topics')
